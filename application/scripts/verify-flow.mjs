import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
fs.mkdirSync('qa',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1536,height:1024},deviceScaleFactor:1});
const errors=[];const requests=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
page.on('response',r=>{if(r.url().includes('/api/'))requests.push({url:r.url(),status:r.status()});});
await page.goto('http://localhost:4173/',{waitUntil:'networkidle'});
// Sign-in is required. The flow below walks every surface, so it signs in as the
// platform administrator, the one role that may open all of them.
await page.getByRole('button',{name:'Sign in with a username instead'}).click();
await page.getByLabel('Username').fill('admin');
await page.getByLabel('Password').fill(process.env.AAVAS_UI_PASSWORD||'Admin@2026');
await page.getByRole('button',{name:'Sign in',exact:true}).click();
await expect(page.getByText('Pricing Service Connected')).toBeVisible();
await page.screenshot({path:'qa/dashboard-desktop.png'});
await page.getByLabel('Filter branch').selectOption('Jaipur');
await expect(page.locator('.kpi').first()).toContainText('1,842');
await page.getByLabel('Filter branch').selectOption('All Branches');
await page.getByRole('button',{name:'Customer Portal',exact:true}).click();
await page.getByRole('button',{name:'Continue to Loan & Property'}).click();
await page.getByRole('checkbox',{name:'I agree to Aavas processing'}).check();
await page.getByRole('button',{name:'See My Indicative Offer'}).click();
await expect(page.getByRole('button',{name:'Open Assessment Workspace'})).toBeVisible({timeout:30000});
await page.getByRole('button',{name:'Basic Information'}).click();
await page.getByRole('button',{name:'Dismiss notification'}).click();
await page.screenshot({path:'qa/offer-desktop.png'});
await page.getByRole('button',{name:'Staff Workspace'}).click();
// The file prices itself when it opens; there is no button to press.
await expect(page.locator('.scenario-slider')).toBeVisible({timeout:60000});
await page.getByRole('button',{name:/^Table of all \d+ scenarios$/}).click();
await expect(page.locator('.scenario-table tbody tr')).not.toHaveCount(0);
await page.getByRole('button',{name:'Slider view',exact:true}).click();
await expect(page.locator('.drivers')).toContainText('Bureau score');
if(await page.getByRole('button',{name:'Dismiss notification'}).count()) await page.getByRole('button',{name:'Dismiss notification'}).click();
await page.screenshot({path:'qa/application-desktop.png'});
await page.getByRole('button',{name:'Value Breakdown',exact:true}).click();
await expect(page.locator('.value-breakdown')).toContainText('Net Annual Margin');
await page.getByRole('button',{name:'Key Drivers',exact:true}).click();
await page.getByLabel('Proposed Final Rate (%)').fill('11.09');
await page.getByLabel('Comments', {exact:true}).fill('Synthetic browser verification: negotiated customer rate.');
await page.getByRole('button',{name:'Record Override',exact:true}).click();
await expect(page.getByText('Recorded at 11.09%')).toBeVisible({timeout:30000});
await page.getByRole('button',{name:'Record Outcome',exact:true}).click();
await page.getByRole('checkbox',{name:'I confirm this reflects'}).check();
await page.getByRole('button',{name:'Confirm & Record'}).click();
await expect(page.getByRole('button',{name:'Outcome Recorded',exact:true})).toBeVisible({timeout:30000});
await page.getByRole('button',{name:'Audit Trail',exact:true}).click();
await expect(page.getByRole('heading',{name:'Capture Outcome',exact:true})).toBeVisible({timeout:30000});
await expect(page.getByRole('heading',{name:'Capture Override',exact:true})).toBeVisible();
await page.screenshot({path:'qa/audit-desktop.png'});
await page.goto('http://localhost:4173/#/models',{waitUntil:'networkidle'});
await expect(page.getByRole('heading',{name:'Stage2 Model'})).toBeVisible();
await page.goto('http://localhost:4173/#/learning',{waitUntil:'networkidle'});
await expect(page.getByRole('heading',{name:'Override reason review'})).toBeVisible({timeout:30000});
await page.goto('http://localhost:4173/#/policy',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Find Policy Clauses'}).click();
await expect(page.getByText('Clause 1',{exact:true})).toBeVisible({timeout:30000});
await page.goto('http://localhost:4173/#/application',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Edit applicant details'}).click();
await page.getByLabel('Bureau score',{exact:true}).fill('0');
await page.getByRole('button',{name:'Save details'}).click();
await expect(page.getByRole('dialog')).toBeVisible();
const invalid=await page.getByLabel('Bureau score',{exact:true}).evaluate(el=>!el.validity.valid);
if(!invalid)throw new Error('Bureau score 0 should be rejected in the UI');
await page.getByRole('button',{name:'Close dialog'}).click();
if(await page.getByRole('button',{name:'Dismiss notification'}).count()) await page.getByRole('button',{name:'Dismiss notification'}).click();
await page.setViewportSize({width:390,height:844});
await page.goto('http://localhost:4173/#/dashboard',{waitUntil:'networkidle'});
await page.screenshot({path:'qa/dashboard-mobile.png',fullPage:true});
let overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw new Error('Dashboard overflows mobile viewport');
await page.getByRole('button',{name:'Open navigation'}).click();
await page.getByRole('button',{name:'Customer Portal',exact:true}).click();
await page.screenshot({path:'qa/offer-mobile.png',fullPage:true});
overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw new Error('Customer portal overflows mobile viewport');
await page.getByRole('button',{name:'Staff Workspace'}).click();
await page.screenshot({path:'qa/application-mobile.png',fullPage:true});
overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw new Error('Assessment overflows mobile viewport');
fs.writeFileSync('qa/verification.json',JSON.stringify({errors,requests,bureauScoreValidation:invalid,mobileOverflow:overflow},null,2));
console.log(JSON.stringify({errors,apiRequests:requests.length,failed:requests.filter(r=>r.status>=400)},null,2));
if(errors.length)throw new Error(errors.join('\n'));
await browser.close();
