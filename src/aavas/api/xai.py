"""Explainability endpoints for the admin view.

Serves the offline OmniXAI pass - one brief per model plus the dashboard
captures - so a model-risk reviewer can read what a model does across the book
without starting six dashboard processes at 1.5 GB each.

The reports are generated by ``make xai`` into ``reports/omnixai/``. When they
are absent the endpoints say so plainly rather than 404-ing into a blank screen;
a stale or missing report is itself a governance finding.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any

from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse, PlainTextResponse

from ..logging_utils import get_logger
from ..paths import OMNIXAI_DIR

log = get_logger(__name__)
router = APIRouter(prefix="/xai", tags=["explainability"])

# Rank agreement between two methods that share no machinery. Below the lower
# bound the global ranking is a property of the method, not of the model.
TRUST_READ = [(0.85, "strong", "read the ranking"),
              (0.60, "moderate", "read with care"),
              (0.00, "weak", "do not lean on the ranking")]


def _models() -> list[str]:
    if not OMNIXAI_DIR.exists():
        return []
    return sorted(d.name for d in OMNIXAI_DIR.iterdir()
                  if d.is_dir() and d.name != "ui" and (d / "analysis.json").exists())


def _load(model: str) -> dict[str, Any]:
    path = OMNIXAI_DIR / model / "analysis.json"
    if not path.exists():
        raise HTTPException(404, f"no explainability report for {model!r}. Run `make xai`.")
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def _trust(agreement: float | None) -> dict[str, Any]:
    if agreement is None:
        return {"level": "unknown", "reading": "rank agreement not computed"}
    for floor, level, reading in TRUST_READ:
        if agreement >= floor:
            return {"level": level, "reading": reading}
    return {"level": "weak", "reading": "do not lean on the ranking"}


def _age_days(generated_at: str | None) -> float | None:
    if not generated_at:
        return None
    try:
        stamp = datetime.fromisoformat(generated_at)
    except ValueError:
        return None
    if stamp.tzinfo is None:
        stamp = stamp.replace(tzinfo=timezone.utc)
    return round((datetime.now(timezone.utc) - stamp).total_seconds() / 86400, 1)


def _captures(model: str) -> list[dict[str, str]]:
    """Dashboard screenshots, if the OmniXAI UI was captured for this model."""
    ui = OMNIXAI_DIR / "ui"
    if not ui.exists():
        return []
    labels = {"global": "Global importance", "local": "Per-instance explanation",
              "data": "Dataset analysis", "prediction": "Prediction analysis",
              "whatif": "What-if / counterfactual"}
    out = []
    for path in sorted(ui.glob(f"{model}-*.png")):
        view = path.stem.split("-", 1)[1]
        out.append({"view": view, "label": labels.get(view, view.title()),
                    "url": f"/xai/capture/{path.name}"})
    return out


@router.get("", summary="Which models have an explainability report")
def index() -> dict[str, Any]:
    models = _models()
    rows = []
    for name in models:
        try:
            data = _load(name)
        except HTTPException:
            continue
        agreement = data.get("rank_agreement_spearman")
        rows.append({
            "model": name,
            "model_version": data.get("model_version"),
            "learner": data.get("learner"),
            "mode": data.get("mode"),
            "target": data.get("target"),
            "generated_at": data.get("generated_at"),
            "age_days": _age_days(data.get("generated_at")),
            "rank_agreement_spearman": agreement,
            "trust": _trust(agreement),
            "n_features": len(data.get("global_importance") or []),
            "n_instances": len(data.get("instances") or []),
            "captures": len(_captures(name)),
        })
    return {"available": bool(rows), "models": rows,
            "reports_dir": str(OMNIXAI_DIR),
            "note": ("Offline OmniXAI pass. Regenerate with `make xai-reports`."
                     if rows else
                     "No reports found. Run `make xai-install && make xai-reports`.")}


@router.get("/credit-score", summary="What every model does across the credit score")
def credit_score_all() -> dict[str, Any]:
    """The band for every model at once - the cross-model view.

    One model's band answers "what does the score do to this prediction". Six of
    them side by side answer the question a customer actually asks, which is what
    the score does to *them*: the rate they are offered, the risk they are
    assessed at, and whether the engine expects them to leave. Those can point in
    different directions, and only this view shows it.

    Registered before ``/{model}`` on purpose: both are a single path segment and
    FastAPI matches in registration order.
    """
    rows, missing = [], []
    for name in _models():
        try:
            data = _load(name)
        except HTTPException:
            continue
        band = data.get("credit_score")
        if not band:
            missing.append(name)
            continue
        agreement = data.get("rank_agreement_spearman")
        rows.append({"model": name, "model_version": data.get("model_version"),
                     "learner": data.get("learner"), "mode": data.get("mode"),
                     "generated_at": data.get("generated_at"),
                     "age_days": _age_days(data.get("generated_at")),
                     "rank_agreement_spearman": agreement, "trust": _trust(agreement),
                     **band})

    units = sorted({r["units"] for r in rows})
    return {
        "available": bool(rows),
        "models": rows,
        "units": units,
        "without_a_band": missing,
        "note": ("Each model is in its own units, so the curves are only comparable "
                 "within a unit. The bands are computed over scored files only; the "
                 "new-to-credit cohort is reported beside them, never inside them."
                 if rows else
                 "No model carries a credit-score band. Run `make xai-reports`."),
    }


@router.get("/{model}", summary="Global and per-instance explainability for one model")
def detail(model: str, instances: int = 8) -> dict[str, Any]:
    data = _load(model)
    agreement = data.get("rank_agreement_spearman")

    # Trim the per-instance block: the full payload carries every SHAP value for
    # every sampled row, which is far more than a screen can use.
    trimmed = []
    for row in (data.get("instances") or [])[:instances]:
        trimmed.append({
            "loan_id": row.get("loan_id"), "label": row.get("label"),
            "prediction": row.get("prediction"), "actual": row.get("actual"),
            "credit_score": row.get("credit_score"),
            "explained_class": row.get("explained_class"),
            "top3_agreement": row.get("top3_agreement"),
            "shap": (row.get("shap") or [])[:6],
            "lime": (row.get("lime") or [])[:6],
            "counterfactuals": row.get("counterfactuals"),
        })

    return {
        "model": data.get("model"), "model_version": data.get("model_version"),
        "learner": data.get("learner"), "mode": data.get("mode"),
        "target": data.get("target"), "output": data.get("output"),
        "units": data.get("units"), "attribution_units": data.get("attribution_units"),
        "class_names": data.get("class_names"),
        "generated_at": data.get("generated_at"), "age_days": _age_days(data.get("generated_at")),
        "rank_agreement_spearman": agreement, "trust": _trust(agreement),
        "counts": data.get("counts"), "card_metrics": data.get("card_metrics"),
        "global_importance": data.get("global_importance"),
        "credit_score": data.get("credit_score"),
        "pdp_features": sorted((data.get("pdp") or {}).keys()),
        "counterfactual_status": data.get("counterfactual_status"),
        "limitations": data.get("limitations"), "notes": data.get("notes"),
        "config_versions": data.get("config_versions"),
        "instances": trimmed,
        "captures": _captures(model),
    }


@router.get("/{model}/credit-score",
            summary="What one model does at the bottom and top of the credit score")
def credit_score(model: str) -> dict[str, Any]:
    """The score band on its own, for a reviewer who wants only that.

    Absent when the report predates the band, or when the model's feature
    contract has no credit score at all - which is a fact worth returning
    plainly rather than a 404 that reads like a missing file.
    """
    data = _load(model)
    band = data.get("credit_score")
    if not band:
        return {"model": model, "available": False,
                "reason": ("this report predates the credit-score band, or the model's "
                           "contract carries no credit score. Regenerate with "
                           "`make xai-reports`."),
                "generated_at": data.get("generated_at")}
    return {"model": model, "available": True,
            "model_version": data.get("model_version"),
            "generated_at": data.get("generated_at"),
            "age_days": _age_days(data.get("generated_at")), **band}


@router.get("/{model}/report", response_class=PlainTextResponse,
            summary="The written brief for one model")
def report(model: str) -> str:
    path = OMNIXAI_DIR / model / "report.md"
    if not path.exists():
        raise HTTPException(404, f"no written report for {model!r}. Run `make xai-reports`.")
    return path.read_text(encoding="utf-8")


@router.get("/capture/{filename}", summary="An OmniXAI dashboard capture")
def capture(filename: str) -> FileResponse:
    # Defend the path: this serves from a fixed directory, never a traversal.
    if "/" in filename or ".." in filename or not filename.endswith(".png"):
        raise HTTPException(400, "invalid capture name")
    path = OMNIXAI_DIR / "ui" / filename
    if not path.exists():
        raise HTTPException(404, f"no capture named {filename!r}")
    return FileResponse(path, media_type="image/png")
