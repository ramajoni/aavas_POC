#!/usr/bin/env python3
"""Policy kit: build the common structure from the live policy, and validate a lender's policy.

    python scripts/policy_kit.py build [--out DIR]
    python scripts/policy_kit.py validate <policy.yaml> [--cutoffs config/model_config.yaml]

build     Regenerates policy_kit/lending_policy.schema.json, policy_kit/lending_policy.template.yaml
          and the sections table in policy_kit/README.md from config/pricing_policy.yaml plus
          policy_kit/sections.yaml. Run it after any change to the live policy or to sections.yaml.
          With --out DIR it writes the three files there instead (used by the drift test).

validate  Checks a filled-in policy three ways and exits non-zero on any failure:
          1. the JSON Schema, with the YAML path, what was expected and what was found;
             any "<...>" placeholder is reported as "not filled in";
          2. the engine's own consistency checks (aavas.governance.policy_checks.run);
          3. a summary.
"""

from __future__ import annotations

import argparse
import datetime
import json
import re
import sys
import textwrap
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / "policy_kit"
POLICY = ROOT / "config" / "pricing_policy.yaml"
MODEL_CONFIG = ROOT / "config" / "model_config.yaml"
SECTIONS = KIT / "sections.yaml"
SCHEMA_NAME = "lending_policy.schema.json"
TEMPLATE_NAME = "lending_policy.template.yaml"
README_NAME = "README.md"
TABLE_BEGIN = "<!-- BEGIN SECTIONS TABLE (generated by scripts/policy_kit.py build; do not edit) -->"
TABLE_END = "<!-- END SECTIONS TABLE -->"

REQUIREMENTS = ("required", "optional", "jurisdiction")
LINE_LIMIT = 40
PLACEHOLDER = re.compile(r"^\s*<[^<>]*>\s*$")

# --------------------------------------------------------------------------- hand constraints
# kind -> (json types, extra keywords, placeholder text)
KINDS: dict[str, tuple[str, dict[str, Any], str]] = {
    "pct_rate": ("number", {"minimum": 0, "maximum": 100}, "<number: % p.a.>"),
    "pct": ("number", {"minimum": 0, "maximum": 100}, "<number: %>"),
    "bps": ("integer", {}, "<integer: bps>"),
    "fraction": ("number", {"minimum": 0, "maximum": 1}, "<number: fraction 0-1>"),
    "months": ("integer", {"exclusiveMinimum": 0}, "<integer: months>"),
    "years": ("integer", {"exclusiveMinimum": 0}, "<integer: years>"),
    "days": ("integer", {"minimum": 0}, "<integer: days>"),
    "hours": ("integer", {"minimum": 0}, "<integer: hours>"),
    "weight": ("number", {"minimum": 0, "maximum": 100}, "<number: weight, 0-100>"),
    "score": ("number", {"minimum": 0, "maximum": 100}, "<number: score, 0-100>"),
}
# a key whose name is not enough, by exact path (section first, "*" = a company-named key)
PATH_KINDS: dict[tuple[str, ...], str] = {
    ("pricing", "matrix"): "pct_rate",
    ("pricing", "grade_base_roi"): "pct_rate",
    ("pricing", "tenure_adjustment", "add_pct"): "pct_rate",
}
KEY_KINDS = {"quote_band_floor": "pct_rate", "quote_band_ceiling": "pct_rate", "score": "score"}
NULLABLE_PATHS = {("supersedes",), ("based_on_draft_of",)}
STRING_PATTERNS = {("effective_from",): r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$"}
PLACEHOLDER_TEXT = {
    ("policy_version",): "<text: unique policy id, for example XX-POLICY-2026.01>",
    ("supersedes",): "<text: policy_version this file replaces, or null>",
    ("based_on_draft_of",): "<text: draft version, or null>",
    ("effective_from",): "<date: YYYY-MM-DD>",
}
VOCAB_KEYS = ("<your name 1>", "<your name 2>")


def name_kind(key: str) -> str | None:
    if key in KEY_KINDS:
        return KEY_KINDS[key]
    tokens = set(key.split("_"))
    if "bps" in tokens:
        return "bps"
    if tokens & {"foir", "ltv", "probability", "quantile"}:
        return "fraction"
    if tokens & {"months", "month"}:
        return "months"
    if tokens & {"years", "year"}:
        return "years"
    if tokens & {"days"}:
        return "days"
    if tokens & {"hours"}:
        return "hours"
    if tokens & {"roi", "rate", "plr"}:
        return "pct_rate"
    if "pct" in tokens:
        return "pct"
    if tokens & {"weight", "weights"}:
        return "weight"
    return None


def kind_for(path: tuple[str, ...]) -> str | None:
    for i in range(len(path), 0, -1):
        if path[:i] in PATH_KINDS:
            return PATH_KINDS[path[:i]]
    named = [p for p in path if p != "*"]
    return name_kind(named[-1]) if named else None


# --------------------------------------------------------------------------- shapes
class Shape:
    """What a policy node looks like, merged over every example of it in the live file."""

    def __init__(self) -> None:
        self.scalars: set[str] = set()
        self.props: dict[str, Shape] | None = None     # a mapping with fixed names
        self.vocab: Shape | None = None                # a mapping whose names are the company's own
        self.arr: Shape | None = None                  # items of a list
        self.is_arr = False
        self.nullable = False

    def merge(self, other: "Shape") -> "Shape":
        self.scalars |= other.scalars
        self.nullable |= other.nullable
        if other.props is not None:
            self.props = self.props if self.props is not None else {}
            for k, v in other.props.items():
                self.props[k] = self.props[k].merge(v) if k in self.props else v
        if other.vocab is not None:
            self.vocab = self.vocab.merge(other.vocab) if self.vocab else other.vocab
        if other.is_arr:
            self.is_arr = True
            if other.arr is not None:
                self.arr = self.arr.merge(other.arr) if self.arr else other.arr
        return self


def matches(pattern: str, rel: tuple[str, ...]) -> bool:
    parts = () if pattern == "." else tuple(pattern.split("."))
    return len(parts) == len(rel) and all(p == "*" or p == r for p, r in zip(parts, rel))


def infer(node: Any, rel: tuple[str, ...], vocab_paths: list[str]) -> Shape:
    s = Shape()
    if node is None:
        s.nullable = True
    elif isinstance(node, bool):
        s.scalars.add("boolean")
    elif isinstance(node, int):
        s.scalars.add("integer")
    elif isinstance(node, float):
        s.scalars.add("number")
    elif isinstance(node, (str, datetime.date)):
        s.scalars.add("string")
    elif isinstance(node, dict):
        if any(matches(p, rel) for p in vocab_paths):
            merged = Shape()
            for v in node.values():
                merged.merge(infer(v, rel + ("*",), vocab_paths))
            s.vocab = merged
        else:
            s.props = {str(k): infer(v, rel + (str(k),), vocab_paths) for k, v in node.items()}
    elif isinstance(node, list):
        s.is_arr = True
        for item in node:
            s.arr = (s.arr or Shape()).merge(infer(item, rel, vocab_paths))
    return s


# --------------------------------------------------------------------------- schema
def render(sh: Shape, path: tuple[str, ...], required_keys: list[tuple[str, ...]]) -> dict[str, Any]:
    """JSON Schema for a shape. `path` starts with the section name."""
    rel = path[1:]
    alts: list[dict[str, Any]] = []
    if sh.scalars:
        kind = kind_for(path)
        types = sorted(sh.scalars)
        extra: dict[str, Any] = {}
        if kind and set(types) <= {"integer", "number"}:
            ktype, extra, _ = KINDS[kind]
            types = [ktype]
        alt: dict[str, Any] = {"type": types[0] if len(types) == 1 else types}
        alt.update(extra)
        if "string" in types and path in STRING_PATTERNS:
            alt["pattern"] = STRING_PATTERNS[path]
        if "string" in types and path == ("policy_version",):
            alt["minLength"] = 1
        alts.append(alt)
    if sh.props is not None or sh.vocab is not None:
        obj: dict[str, Any] = {"type": "object"}
        if sh.vocab is not None:
            obj["additionalProperties"] = render(sh.vocab, path + ("*",), required_keys)
            obj["minProperties"] = 1
        if sh.props is not None:
            obj["properties"] = {k: render(v, path + (k,), required_keys) for k, v in sh.props.items()}
            need = [k for k in sh.props if any(len(r) > len(rel) and r[:len(rel)] == rel and r[len(rel)] == k
                                               for r in required_keys)]
            if need:
                obj["required"] = need
        alts.append(obj)
    if sh.is_arr:
        arr: dict[str, Any] = {"type": "array"}
        if sh.arr is not None:
            arr["items"] = render(sh.arr, path, required_keys)
        alts.append(arr)
    nullable = sh.nullable or path in NULLABLE_PATHS
    if nullable:
        if len(alts) == 1:
            t = alts[0].get("type", [])
            alts[0]["type"] = (t if isinstance(t, list) else [t]) + ["null"]
        elif alts:
            alts.append({"type": "null"})
        else:
            alts.append({"type": "null"})
    if not alts:
        return {}
    return alts[0] if len(alts) == 1 else {"anyOf": alts}


def build_schema(policy: dict[str, Any], meta: dict[str, Any]) -> dict[str, Any]:
    sections = meta["sections"]
    props: dict[str, Any] = {}
    for name, info in sections.items():
        keys = [tuple(k.split(".")) for k in info.get("engine_read_keys", [])]
        shape = infer(policy[name], (), info.get("vocabulary_paths", []))
        sub = render(shape, (name,), keys)
        desc = f"{info['title']}. {info['purpose']}"
        sub = {"description": desc, "x-requirement": info["requirement"], "x-owner": info["owner"],
               "x-part": info["part"], **sub}
        props[name] = sub
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://example.com/lending-policy.schema.json",
        "title": "Lending pricing policy, common structure",
        "description": ("The shape of a lending pricing policy file. Generated by scripts/policy_kit.py build "
                        "from the live policy and policy_kit/sections.yaml. Extra keys and extra sections are "
                        "allowed; the company's own names are accepted wherever a section says so."),
        "type": "object",
        "properties": props,
        "required": [n for n, i in sections.items() if i["requirement"] == "required"],
    }


# --------------------------------------------------------------------------- template
SAFE_KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def key_text(k: str) -> str:
    return k if SAFE_KEY.match(k) else json.dumps(k, ensure_ascii=False)


def placeholder(sh: Shape, path: tuple[str, ...]) -> str:
    if path in PLACEHOLDER_TEXT:
        return PLACEHOLDER_TEXT[path]
    nullable = sh.nullable or path in NULLABLE_PATHS
    if len(sh.scalars) > 1 and not (sh.scalars <= {"integer", "number"}):
        text = "<text or number>"
    elif sh.scalars <= {"integer", "number"} and sh.scalars:
        kind = kind_for(path)
        if kind:
            text = KINDS[kind][2]
        else:
            text = "<integer>" if sh.scalars == {"integer"} else "<number>"
    elif sh.scalars == {"boolean"}:
        text = "<true|false>"
    elif sh.scalars == {"string"}:
        text = "<text>"
    else:
        text = "<value>"
    if nullable and "null" not in text:
        text = text[:-1] + ", or null>"
    return text


def tmpl(sh: Shape, path: tuple[str, ...]) -> tuple[str | None, list[str]]:
    """(inline text, block lines at zero indent). Exactly one of the two is set."""
    if sh.props is not None or sh.vocab is not None:
        lines: list[str] = []
        if sh.vocab is not None:
            for name in VOCAB_KEYS:
                inline, block = tmpl(sh.vocab, path + ("*",))
                lines += entry(json.dumps(name), inline, block)
        for k, v in (sh.props or {}).items():
            inline, block = tmpl(v, path + (k,))
            note = "  # keys are the company's own names" if v.vocab is not None and not v.props else ""
            lines += entry(key_text(k), inline, block, note)
        return None, lines
    if sh.is_arr:
        if sh.arr is None:
            return "[]", []
        inline, block = tmpl(sh.arr, path)
        if inline is not None:
            return None, [f"- {inline}"]
        return None, ["- " + block[0]] + ["  " + line for line in block[1:]]
    return json.dumps(placeholder(sh, path), ensure_ascii=False), []


def entry(key: str, inline: str | None, block: list[str], note: str = "") -> list[str]:
    if inline is not None:
        return [f"{key}: {inline}{note}"]
    return [f"{key}:{note}"] + ["  " + line for line in block]


def wrap(text: str, prefix: str, first: str | None = None) -> list[str]:
    parts = textwrap.wrap(text, 80 - len(prefix))
    return [(first if i == 0 and first else prefix) + p for i, p in enumerate(parts)]


def build_template(policy: dict[str, Any], meta: dict[str, Any]) -> str:
    out = [
        "# Lending pricing policy: blank template.",
        "#",
        "# Generated by scripts/policy_kit.py build from the common structure. Do not hand-edit",
        "# the structure; copy this file, then fill in the copy.",
        "#",
        "# How to fill it in",
        "#   1. Replace every \"<...>\" placeholder with the company's own value.",
        "#   2. Where a section says keys are the company's own names, replace the two examples",
        "#      with the company's real names (grade labels, segments, property types and so on).",
        "#   3. Delete an optional section only if the company does not use it.",
        "#   4. Rates are annual percentages (13.00 means 13% p.a.). Spreads are in basis points.",
        "#   5. Check the result: python scripts/policy_kit.py validate <your file>",
        "#",
        "# This file is not valid until every placeholder is filled in.",
        "",
    ]
    last_part = None
    for name, info in meta["sections"].items():
        if info["part"] != last_part:
            last_part = info["part"]
            part = meta["parts"][last_part]
            out += ["# " + "=" * 76, f"# PART {last_part}: {part['title'].upper()}"]
            out += wrap(part["summary"], "# ")
            out += ["# " + "=" * 76, ""]
        out += [f"# {info['title']}"]
        out += wrap(info["purpose"], "#                ", "#   Purpose:     ")
        out += [f"#   Requirement: {info['requirement']}", f"#   Owner:       {info['owner']}"]
        if info["company_defined_vocabulary"] and "." in info.get("vocabulary_paths", []):
            out += ["#   Keys:        the company's own names"]
        shape = infer(policy[name], (), info.get("vocabulary_paths", []))
        inline, block = tmpl(shape, (name,))
        out += entry(name, inline, block)
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


# --------------------------------------------------------------------------- README table
def build_table(meta: dict[str, Any]) -> str:
    sections = meta["sections"]
    counts = {r: sum(1 for i in sections.values() if i["requirement"] == r) for r in REQUIREMENTS}
    out = [f"The policy has {len(sections)} sections: {counts['required']} required, "
           f"{counts['optional']} optional and {counts['jurisdiction']} jurisdiction-specific.", ""]
    for letter, part in meta["parts"].items():
        rows = [(n, i) for n, i in sections.items() if i["part"] == letter]
        out += [f"#### Part {letter}: {part['title']}", "", part["summary"], "",
                "| Section | Title | Requirement | Owner | Own key names | Purpose |",
                "| --- | --- | --- | --- | --- | --- |"]
        for n, i in rows:
            own = "yes" if i["company_defined_vocabulary"] else "no"
            out.append(f"| `{n}` | {i['title']} | {i['requirement']} | {i['owner']} | {own} | {i['purpose']} |")
        out.append("")
    return "\n".join(out).rstrip("\n")


def build_readme(readme: str, meta: dict[str, Any]) -> str:
    if TABLE_BEGIN not in readme or TABLE_END not in readme:
        raise SystemExit(f"README.md is missing the table markers:\n  {TABLE_BEGIN}\n  {TABLE_END}")
    head, rest = readme.split(TABLE_BEGIN, 1)
    _, tail = rest.split(TABLE_END, 1)
    return f"{head}{TABLE_BEGIN}\n\n{build_table(meta)}\n\n{TABLE_END}{tail}"


# --------------------------------------------------------------------------- build command
def load_yaml(path: Path) -> Any:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def check_sections(policy: dict[str, Any], meta: dict[str, Any]) -> None:
    sections = meta["sections"]
    missing = [k for k in policy if k not in sections]
    stale = [k for k in sections if k not in policy]
    if missing or stale:
        raise SystemExit(f"sections.yaml and the live policy disagree. Missing from sections.yaml: {missing}. "
                         f"Not in the policy: {stale}.")
    for name, info in sections.items():
        for field in ("part", "title", "purpose", "requirement", "company_defined_vocabulary", "owner",
                      "engine_reads"):
            if field not in info:
                raise SystemExit(f"sections.yaml: {name} has no `{field}`")
        if info["requirement"] not in REQUIREMENTS or info["part"] not in meta["parts"]:
            raise SystemExit(f"sections.yaml: {name} has a bad requirement or part")


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def generate(policy_path: Path = POLICY, sections_path: Path = SECTIONS, readme_path: Path = KIT / README_NAME,
             ) -> dict[str, str]:
    """The text of every generated file, keyed by file name."""
    from jsonschema import Draft202012Validator

    policy, meta = load_yaml(policy_path), load_yaml(sections_path)
    check_sections(policy, meta)
    schema = build_schema(policy, meta)
    Draft202012Validator.check_schema(schema)
    return {
        SCHEMA_NAME: json.dumps(schema, indent=2, ensure_ascii=False) + "\n",
        TEMPLATE_NAME: build_template(policy, meta),
        README_NAME: build_readme(readme_path.read_text(encoding="utf-8"), meta),
    }


def cmd_build(args: argparse.Namespace) -> int:
    out = Path(args.out) if args.out else KIT
    files = generate()
    for name, text in files.items():
        write(out / name, text)
        print(f"wrote {out / name}")
    meta = load_yaml(SECTIONS)
    by_req = {r: sum(1 for i in meta["sections"].values() if i["requirement"] == r) for r in REQUIREMENTS}
    print(f"{len(meta['sections'])} sections: {by_req}")
    return 0


# --------------------------------------------------------------------------- validate command
def normalise(node: Any) -> Any:
    """YAML turns an unquoted 2026-12-01 into a date; the schema wants text."""
    if isinstance(node, dict):
        return {normalise(k): normalise(v) for k, v in node.items()}
    if isinstance(node, list):
        return [normalise(v) for v in node]
    if isinstance(node, (datetime.date, datetime.datetime)):
        return node.isoformat()
    return node


def dotted(path: Any) -> str:
    out = ""
    for p in path:
        out += f"[{p}]" if isinstance(p, int) else (f".{p}" if out else str(p))
    return out or "(file)"


def unfilled(node: Any, path: tuple = ()) -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    if isinstance(node, dict):
        for k, v in node.items():
            if isinstance(k, str) and PLACEHOLDER.match(k):
                found.append((dotted(path + (k,)), k))
            found += unfilled(v, path + (k,))
    elif isinstance(node, list):
        for i, v in enumerate(node):
            found += unfilled(v, path + (i,))
    elif isinstance(node, str) and PLACEHOLDER.match(node):
        found.append((dotted(path), node.strip()))
    return found


def found_text(value: Any) -> str:
    kind = {bool: "true/false", int: "integer", float: "number", str: "text", list: "list",
            dict: "mapping", type(None): "null"}.get(type(value), type(value).__name__)
    shown = json.dumps(value, default=str, ensure_ascii=False)
    return f"{shown[:60]}{'...' if len(shown) > 60 else ''} ({kind})"


def describe(err: Any) -> str:
    from jsonschema.exceptions import best_match

    leaf = err
    while leaf.validator in ("anyOf", "oneOf") and leaf.context:
        leaf = best_match(leaf.context) or leaf.context[0]
    v, want = leaf.validator, leaf.validator_value
    if v == "required":
        missing = [k for k in want if k not in (leaf.instance or {})]
        return f"missing required key {', '.join(repr(m) for m in missing)}"
    if v == "type":
        names = want if isinstance(want, list) else [want]
        return f"expected {' or '.join(names)}, found {found_text(leaf.instance)}"
    bounds = {"minimum": "a number >= {}", "maximum": "a number <= {}",
              "exclusiveMinimum": "a number > {}", "exclusiveMaximum": "a number < {}",
              "minProperties": "at least {} entries", "minLength": "text of at least {} characters"}
    if v in bounds:
        return f"expected {bounds[v].format(want)}, found {found_text(leaf.instance)}"
    if v == "pattern":
        return f"expected text matching {want}, found {found_text(leaf.instance)}"
    return f"{leaf.message[:160]}"


def schema_problems(policy: dict[str, Any], schema: dict[str, Any]) -> tuple[list[str], list[str]]:
    """(not filled in, other schema errors) as printable lines."""
    from jsonschema import Draft202012Validator

    holes = unfilled(policy)
    hole_paths = {p for p, _ in holes}
    lines = [f"{p}: not filled in (found {v})" for p, v in dict.fromkeys(holes)]
    errors: list[str] = []
    for err in sorted(Draft202012Validator(schema).iter_errors(policy), key=lambda e: [str(p) for p in e.path]):
        if isinstance(err.instance, str) and PLACEHOLDER.match(err.instance):
            continue                                     # reported once, as not filled in
        where = dotted(err.absolute_path)
        if where in hole_paths:
            continue
        errors.append(f"{where}: {describe(err)}")
    return lines, errors


def cmd_validate(args: argparse.Namespace) -> int:
    sys.path.insert(0, str(ROOT / "src"))
    path = Path(args.policy)
    try:
        policy = normalise(load_yaml(path))
    except (OSError, yaml.YAMLError) as exc:
        print(f"FAIL cannot read {path}: {exc}")
        return 1
    if not isinstance(policy, dict):
        print(f"FAIL {path} is not a YAML mapping of sections")
        return 1
    schema = json.loads((KIT / SCHEMA_NAME).read_text(encoding="utf-8"))
    meta = load_yaml(SECTIONS)
    failures = 0

    print(f"1. Schema ({SCHEMA_NAME})")
    holes, errors = schema_problems(policy, schema)
    shown = holes + errors if args.verbose else (errors + holes)[:LINE_LIMIT]
    for line in shown:
        print(f"   FAIL {line}")
    if len(holes) + len(errors) > len(shown):
        print(f"   ... and {len(holes) + len(errors) - len(shown)} more (use --verbose to list them all)")
    if not holes and not errors:
        print("   PASS the file matches the common structure")
    failures += len(holes) + len(errors)

    print("2. Engine checks (policy_checks.run)")
    check_failed = 0
    try:
        from aavas.governance import policy_checks

        cutoffs = load_yaml(Path(args.cutoffs))["risk"]["grade_cutoffs"]
        results = policy_checks.run(policy, cutoffs)
        for r in results:
            word = "SKIP" if r["ok"] is None else ("PASS" if r["ok"] else "FAIL")
            if word == "FAIL" or args.verbose:
                print(f"   {word} {r['check']}" + (f"  {r['detail']}" if r["detail"] else ""))
        s = policy_checks.summary(results)
        check_failed = len(s["failed"])
        print(f"   {s['passed']} passed, {check_failed} failed, {s['skipped']} skipped of {s['checks']}")
    except Exception as exc:                              # noqa: BLE001 - an incomplete file may break any check
        check_failed = 1
        print(f"   FAIL the engine checks could not run on this file ({type(exc).__name__}: {exc})")
    failures += check_failed

    sections = meta["sections"]
    required = [n for n, i in sections.items() if i["requirement"] == "required"]
    extra = [k for k in policy if k not in sections]
    print("3. Summary")
    print(f"   file: {path}  policy_version: {policy.get('policy_version')}")
    print(f"   required sections present: {sum(1 for n in required if n in policy)} of {len(required)}")
    absent = [n for n, i in sections.items() if i["requirement"] != "required" and n not in policy]
    print(f"   optional and jurisdiction sections present: "
          f"{sum(1 for n, i in sections.items() if i['requirement'] != 'required' and n in policy)} "
          f"of {len(sections) - len(required)}" + (f" (absent: {', '.join(absent)})" if absent else ""))
    if extra:
        print(f"   extra sections kept, not checked by the schema: {', '.join(extra)}")
    print(f"   not filled in: {len(holes)}   schema errors: {len(errors)}   engine check failures: {check_failed}")
    print("   RESULT: " + ("PASS" if not failures else "FAIL"))
    return 0 if not failures else 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="regenerate the schema, template and README table")
    b.add_argument("--out", help="write the generated files here instead of policy_kit/")
    v = sub.add_parser("validate", help="validate a policy file")
    v.add_argument("policy")
    v.add_argument("--cutoffs", default=str(MODEL_CONFIG), help="model config holding risk.grade_cutoffs")
    v.add_argument("--verbose", action="store_true", help="list every engine check, not only failures")
    args = ap.parse_args(argv)
    return cmd_build(args) if args.cmd == "build" else cmd_validate(args)


